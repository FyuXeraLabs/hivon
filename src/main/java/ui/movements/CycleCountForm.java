    private void btnAddToSummaryActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAddToSummaryActionPerformed
        int idx = listMaterials.getSelectedIndex();
        if (idx < 0 || idx >= countItems.size()) {
            StatusMessageHandler.showError(txtStatus, "Please select a material from the list.");
            return;
        }

        CycleCountItemDTO item = countItems.get(idx);
        double countedQty;
        try {
            spinCountedQty.commitEdit();
            countedQty = ((Number) spinCountedQty.getValue()).doubleValue();
        } catch (Exception e) {
            StatusMessageHandler.showError(txtStatus, "Please enter a valid counted quantity.");
            return;
        }

        if (countedQty < 0) {
            StatusMessageHandler.showError(txtStatus, "Counted quantity cannot be negative.");
            return;
        }

        item.setCountedQuantity(countedQty);
        String remarks = txtaRemarks.getText().trim();
        item.setVarianceReason(remarks.isEmpty() ? null : remarks);
        item.setRecountRequired(chkRecountRequired.isSelected());

        // Update list display
        materialListModel.set(idx, formatListItem(item));

        // Update summary table
        refreshSummaryTable();
        highlightSummaryRow(idx);

        // Async save to API so progress is persisted
        saveItemCountToApi(item);

        StatusMessageHandler.showSuccess(txtStatus, "Count recorded for " + item.getMaterialCode() + " (" + countedQty + ").");

        // UX: Auto-advance to next uncounted item
        int nextUncounted = findNextUncountedIndex(idx);
        if (nextUncounted != -1) {
            selectMaterialIndex(nextUncounted);
        } else if (idx < countItems.size() - 1) {
            selectMaterialIndex(idx + 1);
        } else {
            StatusMessageHandler.showInfo(txtStatus, "All items counted! Review the summary and click 'Complete Count'.");
        }
    }//GEN-LAST:event_btnAddToSummaryActionPerformed

