    private void loadWarehouses() {
        BackgroundTask task = new BackgroundTask(this, "Loading Warehouses") {
            private List<WarehouseDTO> warehouses;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Fetching warehouses from server...");
                warehouses = controller.getWarehouses();
                return warehouses != null;
            }

            @Override
            protected void onSuccess() {
                loadedWarehouses = warehouses != null ? warehouses : new ArrayList<>();
                isProgrammaticSelection = true;
                cmbWarehouse.removeAllItems();
                cmbWarehouse.addItem("-- Select Warehouse --");

                Integer userWhId = null;
                try {
                    if (UserSession.getInstance().getCurrentUser() != null) {
                        userWhId = UserSession.getInstance().getCurrentUser().getWarehouseId();
                    }
                } catch (Exception ignored) {}

                int selectIdx = 0;
                for (int i = 0; i < loadedWarehouses.size(); i++) {
                    WarehouseDTO wh = loadedWarehouses.get(i);
                    cmbWarehouse.addItem(wh.getWarehouseCode() + " - " + wh.getWarehouseName());
                    if (userWhId != null && wh.getWarehouseId() != null && wh.getWarehouseId().equals(userWhId)) {
                        selectIdx = i + 1;
                    }
                }

                if (selectIdx > 0) {
                    cmbWarehouse.setSelectedIndex(selectIdx);
                }
                isProgrammaticSelection = false;

                if (selectIdx > 0) {
                    onWarehouseChanged();
                }
                StatusMessageHandler.showSuccess(txtStatus, "Ready for Cycle Count.");
            }

            @Override
            protected void onFailure(Exception e) {
                StatusMessageHandler.showError(txtStatus, "Failed to load warehouses: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }

    private WarehouseDTO getSelectedWarehouse() {
        int idx = cmbWarehouse.getSelectedIndex() - 1;
        if (idx >= 0 && idx < loadedWarehouses.size()) {
            return loadedWarehouses.get(idx);
        }
        return null;
    }

    private void onWarehouseChanged() {
        WarehouseDTO wh = getSelectedWarehouse();
        clearBinDetails();
        clearCountDetails();

        if (wh == null) {
            isProgrammaticSelection = true;
            cmbZone.removeAllItems();
            cmbZone.addItem("-- All / Select Zone --");
            cmbBin.removeAllItems();
            cmbBin.addItem("-- Select Bin --");
            isProgrammaticSelection = false;
            return;
        }

        loadZonesAndBins(wh.getWarehouseId());
    }

    private void loadZonesAndBins(int warehouseId) {
        BackgroundTask task = new BackgroundTask(this, "Loading Zones & Bins") {
            private List<ZoneDTO> zones;
            private List<StorageBinDTO> bins;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Loading zones and bins for warehouse...");
                zones = controller.getZones(warehouseId);
                bins = controller.getBins(warehouseId, null);
                return true;
            }

            @Override
            protected void onSuccess() {
                loadedZones = zones != null ? zones : new ArrayList<>();
                loadedBins = bins != null ? bins : new ArrayList<>();

                isProgrammaticSelection = true;
                cmbZone.removeAllItems();
                cmbZone.addItem("-- All / Select Zone --");
                for (ZoneDTO z : loadedZones) {
                    cmbZone.addItem(z.getZoneCode() + (z.getZoneName() != null ? " - " + z.getZoneName() : ""));
                }

                populateBinCombo(loadedBins);
                isProgrammaticSelection = false;
                StatusMessageHandler.showInfo(txtStatus, "Loaded " + loadedBins.size() + " storage bins.");
            }

            @Override
            protected void onFailure(Exception e) {
                StatusMessageHandler.showError(txtStatus, "Failed to load zones and bins: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }

