    private void btnStartCountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnStartCountActionPerformed
        WarehouseDTO wh = getSelectedWarehouse();
        if (wh == null) {
            StatusMessageHandler.showError(txtStatus, "Please select a Warehouse.");
            return;
        }

        ZoneDTO zone = getSelectedZone();
        StorageBinDTO bin = getSelectedBin();

        if (bin == null && zone == null) {
            StatusMessageHandler.showError(txtStatus, "Please select a specific Bin or Zone to count.");
            return;
        }

        String countReason = (String) cmbCountReason.getSelectedItem();
        if (countReason == null) countReason = "SCHEDULED";

        Date date = datepickerDate.getDate();
        if (date == null) date = new Date();
        String dateStr = new SimpleDateFormat("yyyy-MM-dd").format(date);

        final Integer binId = bin != null ? bin.getBinId() : null;
        final String zoneCode = zone != null ? zone.getZoneCode() : (bin != null ? bin.getZoneCode() : null);
        final String finalReason = countReason;
        final String finalDate = dateStr;
        final int whId = wh.getWarehouseId();

        BackgroundTask task = new BackgroundTask(this, "Starting Cycle Count") {
            private CycleCountDTO countDTO;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Initiating cycle count and freezing bins...");
                countDTO = controller.startCycleCount(whId, binId, zoneCode, finalDate, finalReason);
                return countDTO != null;
            }

            @Override
            protected void onSuccess() {
                currentCycleCount = countDTO;
                countItems = countDTO.getItems() != null ? new ArrayList<>(countDTO.getItems()) : new ArrayList<>();

                // update bin status in UI
                tblBinStatus.setText("FROZEN");
                btnFreeze.setEnabled(false);
                btnUnfreeze.setEnabled(true);

                // populate listMaterials
                populateMaterialList();

                // populate summary table
                refreshSummaryTable();

                if (countItems.isEmpty()) {
                    StatusMessageHandler.showWarning(txtStatus, "Count started (" + countDTO.getCountNumber() + "), but no materials found in selected bin/zone.");
                    updateCountControlsEnabled(false);
                } else {
                    StatusMessageHandler.showSuccess(txtStatus, "Cycle Count " + countDTO.getCountNumber() + " started! " + countItems.size() + " material(s) loaded.");
                    updateCountControlsEnabled(true);
                    selectMaterialIndex(0);
                }

                btnCompleteCount.setEnabled(true);
                btnStartCount.setEnabled(false);
                cmbWarehouse.setEnabled(false);
                cmbZone.setEnabled(false);
                cmbBin.setEnabled(false);
                cmbCountReason.setEnabled(false);
                datepickerDate.setEnabled(false);
            }

            @Override
            protected void onFailure(Exception e) {
                StatusMessageHandler.showError(txtStatus, "Failed to start cycle count: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }//GEN-LAST:event_btnStartCountActionPerformed

    private void btnCompleteCountActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCompleteCountActionPerformed
        if (currentCycleCount == null) {
            StatusMessageHandler.showError(txtStatus, "No active cycle count to complete.");
            return;
        }

        int uncountedCount = 0;
        for (CycleCountItemDTO it : countItems) {
            if (!it.isCounted()) {
                uncountedCount++;
            }
        }

        if (uncountedCount > 0) {
            int confirm = JOptionPane.showConfirmDialog(
                    this,
                    "There are " + uncountedCount + " uncounted item(s).\nUncounted items will be saved with counted quantity = 0.\nDo you want to complete the count?",
                    "Confirm Complete Count",
                    JOptionPane.YES_NO_OPTION,
                    JOptionPane.WARNING_MESSAGE
            );
            if (confirm != JOptionPane.YES_OPTION) {
                return;
            }
            for (CycleCountItemDTO it : countItems) {
                if (!it.isCounted()) {
                    it.setCountedQuantity(0.0);
                    it.setVarianceReason("Uncounted - defaulted to 0");
                }
            }
        }

        final int countId = currentCycleCount.getCountId();
        final List<CycleCountItemDTO> allItems = new ArrayList<>(countItems);

        BackgroundTask task = new BackgroundTask(this, "Completing Cycle Count") {
            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Saving final physical counts...");
                controller.recordCounts(countId, allItems);

                updateProgress("Finalizing count, posting variance adjustments, and unfreezing bins...");
                return controller.completeCycleCount(countId);
            }

            @Override
            protected void onSuccess() {
                StatusMessageHandler.showSuccess(txtStatus, "Cycle Count " + currentCycleCount.getCountNumber() + " completed successfully! Adjustments posted.");
                tblBinStatus.setText("ACTIVE");
                btnFreeze.setEnabled(true);
                btnUnfreeze.setEnabled(false);
                btnCompleteCount.setEnabled(false);
                updateCountControlsEnabled(false);

                JOptionPane.showMessageDialog(
                        CycleCountForm.this,
                        "Cycle Count " + currentCycleCount.getCountNumber() + " completed successfully!\n" +
                                "All stock adjustments (INT19) have been posted and bins unfrozen.",
                        "Count Completed",
                        JOptionPane.INFORMATION_MESSAGE
                );
            }

            @Override
            protected void onFailure(Exception e) {
                StatusMessageHandler.showError(txtStatus, "Failed to complete cycle count: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }//GEN-LAST:event_btnCompleteCountActionPerformed

