    private void initCustomLogic() {
        // Load filter dropdowns
        loadFilterOptions();

        // Configure table sorting
        rowSorter = new TableRowSorter<>((DefaultTableModel) tblMaterial.getModel());
        tblMaterial.setRowSorter(rowSorter);

        // Color-coding cell renderer for Expiring/Expired items
        tblMaterial.setDefaultRenderer(Object.class, new DefaultTableCellRenderer() {
            @Override
            public Component getTableCellRendererComponent(JTable table, Object value,
                    boolean isSelected, boolean hasFocus, int row, int column) {
                Component c = super.getTableCellRendererComponent(table, value, isSelected, hasFocus, row, column);

                if (!isSelected && chkHighlight.isSelected()) {
                    try {
                        int modelRow = table.convertRowIndexToModel(row);
                        Object expVal = table.getModel().getValueAt(modelRow, 6); // Expire Date column

                        if (expVal != null && !expVal.toString().trim().isEmpty() && !"N/A".equalsIgnoreCase(expVal.toString().trim())) {
                            LocalDate expDate = LocalDate.parse(expVal.toString().trim());
                            LocalDate today = LocalDate.now();

                            if (expDate.isBefore(today)) {
                                // Expired (Soft Red)
                                c.setBackground(new Color(254, 226, 226));
                                c.setForeground(new Color(153, 27, 27));
                            } else if (!expDate.isAfter(today.plusDays(30))) {
                                // Expiring soon <= 30 days (Soft Amber)
                                c.setBackground(new Color(254, 243, 199));
                                c.setForeground(new Color(146, 64, 14));
                            } else {
                                c.setBackground(Color.WHITE);
                                c.setForeground(new Color(30, 41, 59));
                            }
                        } else {
                            c.setBackground(Color.WHITE);
                            c.setForeground(new Color(30, 41, 59));
                        }
                    } catch (Exception ex) {
                        c.setBackground(Color.WHITE);
                        c.setForeground(new Color(30, 41, 59));
                    }
                } else if (!isSelected) {
                    c.setBackground(Color.WHITE);
                    c.setForeground(new Color(30, 41, 59));
                }
                return c;
            }
        });

        // Add Enter key listeners to table filter text fields
        KeyAdapter enterKeyAdapter = new KeyAdapter() {
            @Override
            public void keyPressed(KeyEvent e) {
                if (e.getKeyCode() == KeyEvent.VK_ENTER) {
                    applyTableFilter();
                }
            }
        };
        txtMaterialCodeFilter.addKeyListener(enterKeyAdapter);
        txtBatchNummberFilter.addKeyListener(enterKeyAdapter);
        txtStorageBinFilter.addKeyListener(enterKeyAdapter);

        // Reset display
        resetFormDisplay();
    }

    private void loadFilterOptions() {
        BackgroundTask task = new BackgroundTask(this, "Loading Filter Options") {
            private List<MaterialDTO> materials;
            private List<BatchDTO> batches;
            private List<StorageBinDTO> bins;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Fetching materials, batches, and bins...");
                materials = controller.getMaterials();
                batches = controller.getBatches();
                bins = controller.getBins();
                return true;
            }

            @Override
            protected void onSuccess() {
                cmdMaterialCode.removeAllItems();
                cmdMaterialCode.addItem("All");
                if (materials != null) {
                    for (MaterialDTO m : materials) {
                        if (m.getMaterialCode() != null) {
                            cmdMaterialCode.addItem(m.getMaterialCode());
                        }
                    }
                }

                cmbBatchNumber.removeAllItems();
                cmbBatchNumber.addItem("All");
                if (batches != null) {
                    for (BatchDTO b : batches) {
                        if (b.getBatchNumber() != null) {
                            cmbBatchNumber.addItem(b.getBatchNumber());
                        }
                    }
                }

                cmbStorageBin.removeAllItems();
                cmbStorageBin.addItem("All");
                if (bins != null) {
                    for (StorageBinDTO bin : bins) {
                        if (bin.getBinCode() != null) {
                            cmbStorageBin.addItem(bin.getBinCode());
                        }
                    }
                }
            }

            @Override
            protected void onFailure(Exception e) {
                Logger.errlog("Failed to load filter options in MaterialMonitoringForm", e);
                StatusMessageHandler.showError(txtStatus, "Failed to load filters: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }

    private String getSelectedFilter(ui.components.CheckedComboBox<String> combo) {
        Set<String> selected = combo.getSelectedItems();
        if (selected != null && !selected.isEmpty()) {
            return String.join(",", selected);
        }
        Object item = combo.getSelectedItem();
        if (item != null) {
            return item.toString();
        }
        return "All";
    }

    private void generateReport() {
        String materialFilter = getSelectedFilter(cmdMaterialCode);
        String batchFilter = getSelectedFilter(cmbBatchNumber);
        String binFilter = getSelectedFilter(cmbStorageBin);
        boolean highlightExpiring = chkHighlight.isSelected();

        BackgroundTask task = new BackgroundTask(this, "Analyzing Material Stock & Batches") {
            private MaterialMonitoringReportDTO dto;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Analyzing inventory records and batch traceability...");
                dto = controller.generateMaterialMonitoringReport(
                    materialFilter, batchFilter, binFilter, highlightExpiring
                );
                return dto != null;
            }

            @Override
            protected void onSuccess() {
                if (dto != null) {
                    displayReport(dto);
                } else {
                    StatusMessageHandler.showWarning(txtStatus, "No records found for selected filters.");
                }
            }

            @Override
            protected void onFailure(Exception e) {
                Logger.errlog("Material monitoring analysis failed", e);
                StatusMessageHandler.showError(txtStatus, "Analysis failed: " + e.getMessage());
            }
        };
        task.executeWithDialog();
    }

    private void displayReport(MaterialMonitoringReportDTO dto) {
        currentReportData = dto;

        // KPI card updates
        lblActiveInventorySkills.setText(String.valueOf(dto.getActiveInventorySkus()));
        jLabel3.setText(qtyFmt.format(dto.getTotalQuantity()));
        jLabel6.setText(dto.getCurrency() != null ? dto.getCurrency() : "$");
        jLabel5.setText(currencyFmt.format(dto.getTotalInventoryValue()));
        jLabel8.setText(String.valueOf(dto.getExpiringCount()));
        jLabel10.setText(String.format("%.1f%%", dto.getAvgBinCapacityUsage()));

        // Populate table
        DefaultTableModel model = (DefaultTableModel) tblMaterial.getModel();
        model.setRowCount(0);

        if (dto.getItems() != null) {
            for (MaterialMonitoringItem item : dto.getItems()) {
                model.addRow(new Object[]{
                    item.getMaterialCode(),
                    item.getBatchNumber(),
                    item.getStorageBin(),
                    qtyFmt.format(item.getQuantity()),
                    String.format("%.1f%%", item.getBinCapacityPct()),
                    item.getManufactureDate(),
                    item.getExpiryDate(),
                    currencyFmt.format(item.getBatchCost()),
                    currencyFmt.format(item.getLineValue())
                });
            }
        }

        // Apply quick table filter if any is active
        applyTableFilter();

        int recordCount = dto.getItems() != null ? dto.getItems().size() : 0;
        StatusMessageHandler.showSuccess(txtStatus, "Material monitoring report generated (" + recordCount + " records).");
    }

    private void applyTableFilter() {
        if (rowSorter == null) return;

        String matFilter = txtMaterialCodeFilter.getText().trim();
        String batchFilter = txtBatchNummberFilter.getText().trim();
        String binFilter = txtStorageBinFilter.getText().trim();

        List<RowFilter<Object, Object>> filters = new ArrayList<>();

        if (!matFilter.isEmpty()) {
            filters.add(RowFilter.regexFilter("(?i)" + Pattern.quote(matFilter), 0));
        }
        if (!batchFilter.isEmpty()) {
            filters.add(RowFilter.regexFilter("(?i)" + Pattern.quote(batchFilter), 1));
        }
        if (!binFilter.isEmpty()) {
            filters.add(RowFilter.regexFilter("(?i)" + Pattern.quote(binFilter), 2));
        }

        if (filters.isEmpty()) {
            rowSorter.setRowFilter(null);
        } else {
            rowSorter.setRowFilter(RowFilter.andFilter(filters));
            StatusMessageHandler.showInfo(txtStatus, "Filter applied: " + tblMaterial.getRowCount() + " visible records.");
        }
    }

    private void resetFormDisplay() {
        currentReportData = null;

        if (cmdMaterialCode.getItemCount() > 0) cmdMaterialCode.setSelectedIndex(0);
        if (cmbBatchNumber.getItemCount() > 0) cmbBatchNumber.setSelectedIndex(0);
        if (cmbStorageBin.getItemCount() > 0) cmbStorageBin.setSelectedIndex(0);
        chkHighlight.setSelected(false);

        txtMaterialCodeFilter.setText("");
        txtBatchNummberFilter.setText("");
        txtStorageBinFilter.setText("");

        if (rowSorter != null) {
            rowSorter.setRowFilter(null);
        }

        lblActiveInventorySkills.setText("0");
        jLabel3.setText("0");
        jLabel6.setText("$");
        jLabel5.setText("0.00");
        jLabel8.setText("0");
        jLabel10.setText("0.0%");

        DefaultTableModel model = (DefaultTableModel) tblMaterial.getModel();
        model.setRowCount(0);

        StatusMessageHandler.clearStatus(txtStatus);
    }

    private void exportReport(String format) {
        if (currentReportData == null || currentReportData.getItems() == null || currentReportData.getItems().isEmpty()) {
            StatusMessageHandler.showWarning(txtStatus, "Please generate a report first before exporting.");
            return;
        }

        JFileChooser fileChooser = new JFileChooser();
        fileChooser.setDialogTitle("Save " + format + " Report");
        String defaultFileName = "MaterialMonitoringReport_" + System.currentTimeMillis() + ("XLSX".equalsIgnoreCase(format) ? ".xlsx" : ".pdf");
        fileChooser.setSelectedFile(new File(defaultFileName));
        if ("XLSX".equalsIgnoreCase(format)) {
            fileChooser.setFileFilter(new FileNameExtensionFilter("Excel Workbook (*.xlsx)", "xlsx"));
        } else {
            fileChooser.setFileFilter(new FileNameExtensionFilter("PDF Document (*.pdf)", "pdf"));
        }
        fileChooser.setAcceptAllFileFilterUsed(false);

        int userSelection = fileChooser.showSaveDialog(this);
        if (userSelection == JFileChooser.APPROVE_OPTION) {
            final File fileToSave = fileChooser.getSelectedFile();
            BackgroundTask task = new BackgroundTask(this, "Exporting Report as " + format) {
                @Override
                protected Boolean performTask() throws Exception {
                    updateProgress("Writing " + format + " report file...");
                    if ("XLSX".equalsIgnoreCase(format)) {
                        MaterialMonitoringReportExportUtils.exportToXLSX(currentReportData, fileToSave);
                    } else {
                        MaterialMonitoringReportExportUtils.exportToPDF(currentReportData, fileToSave);
                    }
                    return true;
                }

                @Override
                protected void onSuccess() {
                    StatusMessageHandler.showSuccess(txtStatus, format + " report exported: " + fileToSave.getName());
                }

                @Override
                protected void onFailure(Exception e) {
                    Logger.errlog("Failed to export report as " + format, e);
                    StatusMessageHandler.showError(txtStatus, "Export failed: " + e.getMessage());
                }
            };
            task.executeWithDialog();
        }
    }

