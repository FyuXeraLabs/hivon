    /**
     * Checks whether there is anything pending to sync and updates UI without blindly triggering sync.
     */
    public void refreshStatus() {
        if (SyncManager.getInstance().isSyncing()) {
            btnSync.setEnabled(false);
            return;
        }

        try {
            int pending = OfflineQueueDAO.getInstance().getPendingCount();
            if (pending > 0) {
                lblDetail.setText(pending + " item(s) yet to sync");
                btnSync.setEnabled(true);
                jProgressBar1.setMinimum(0);
                jProgressBar1.setMaximum(pending);
                jProgressBar1.setValue(0);
                jProgressBar1.setStringPainted(true);
                jProgressBar1.setString("0 / " + pending);
            } else {
                lblDetail.setText("There is nothing to sync");
                btnSync.setEnabled(false);
                jProgressBar1.setValue(0);
                jProgressBar1.setStringPainted(false);
            }
        } catch (Exception e) {
            lblDetail.setText("There is nothing to sync");
            btnSync.setEnabled(false);
            jProgressBar1.setValue(0);
            jProgressBar1.setStringPainted(false);
        }
    }

    /**
     * Triggers sync and updates the progress bar and detail label.
     *
     * @param manual true if clicked by user, false if triggered automatically
     */
    public void triggerSync(boolean manual) {
        if (SyncManager.getInstance().isSyncing()) {
            return;
        }

        if (!UserSession.getInstance().isValid()) {
            if (manual) {
                lblDetail.setText("Please login first to sync data");
            }
            return;
        }

        int pending = OfflineQueueDAO.getInstance().getPendingCount();
        if (pending == 0) {
            lblDetail.setText("There is nothing to sync");
            btnSync.setEnabled(false);
            jProgressBar1.setValue(0);
            jProgressBar1.setStringPainted(false);
            return;
        }

        btnSync.setEnabled(false);
        lblDetail.setText("Checking connection to server...");

        Thread preflight = new Thread(() -> {
            boolean online = SyncManager.getInstance().isOnline();
            if (!online) {
                SwingUtilities.invokeLater(() -> {
                    lblDetail.setText(pending + " item(s) yet to sync (No connection)");
                    btnSync.setEnabled(true);
                });
                return;
            }

            SwingUtilities.invokeLater(() -> {
                lblDetail.setText("Connecting to server...");
                jProgressBar1.setMinimum(0);
                jProgressBar1.setMaximum(pending);
                jProgressBar1.setValue(0);
                jProgressBar1.setStringPainted(true);
                jProgressBar1.setString("0 / " + pending);
            });

            SyncManager.getInstance().syncAllAsync(new SyncManager.SyncProgressListener() {
                @Override
                public void onProgress(int current, int total, String identifier) {
                    SwingUtilities.invokeLater(() -> {
                        jProgressBar1.setMinimum(0);
                        jProgressBar1.setMaximum(total);
                        jProgressBar1.setValue(current);
                        jProgressBar1.setString(current + " / " + total);
                        lblDetail.setText("Syncing " + identifier + " (" + current + "/" + total + ")...");
                    });
                }

                @Override
                public void onItemComplete(int current, int total, core.offline.OfflineRequest req, boolean success, String error) {
                    if (!success && error != null && (error.contains("Connection interrupted") || error.contains("Network"))) {
                        SwingUtilities.invokeLater(() -> {
                            lblDetail.setText("Sync halted: No connection");
                            btnSync.setEnabled(true);
                        });
                    }
                }
            });
        }, "Hivon-SyncPreflight");
        preflight.setDaemon(true);
        preflight.start();
    }

