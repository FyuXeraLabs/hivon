    private static SystemTrayPanel currentInstance;

    /**
     * Closes the panel if currently open and releases resources.
     */
    public static void closePanel() {
        javax.swing.SwingUtilities.invokeLater(() -> {
            if (slideTimer != null && slideTimer.isRunning()) {
                slideTimer.stop();
            }
            if (dialogInstance != null) {
                if (dialogInstance.isDisplayable()) {
                    dialogInstance.getContentPane().removeAll();
                    dialogInstance.dispose();
                }
                dialogInstance = null;
            }
            currentInstance = null;
        });
    }

    public static void showSyncProgress(int total) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            showInDialog();
            if (currentInstance != null) {
                currentInstance.jProgressBar1.setMinimum(0);
                currentInstance.jProgressBar1.setMaximum(total);
                currentInstance.jProgressBar1.setValue(0);
                currentInstance.jProgressBar1.setStringPainted(true);
                currentInstance.lblDetail.setText("Preparing to sync " + total + " items...");
            }
        });
    }

    public static void updateSyncProgress(int current, int total) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            if (currentInstance != null) {
                currentInstance.jProgressBar1.setMinimum(0);
                currentInstance.jProgressBar1.setMaximum(total);
                currentInstance.jProgressBar1.setValue(current);
                currentInstance.jProgressBar1.setString(current + " / " + total);
            }
        });
    }

    public static void updateDetail(String detailText) {
        javax.swing.SwingUtilities.invokeLater(() -> {
            if (currentInstance != null) {
                currentInstance.lblDetail.setText(detailText);
                if (detailText.contains("completed") || detailText.contains("nothing to sync")) {
                    currentInstance.btnSync.setEnabled(false);
                } else if (detailText.contains("halted") || detailText.contains("No connection") || detailText.contains("yet to sync")) {
                    currentInstance.btnSync.setEnabled(true);
                }
            }
        });
    }

    public static void hideSyncProgress() {
        closePanel();
    }

    /**
     * Calculates the resting coordinates for the panel at bottom right up to the taskbar.
     */
    public static java.awt.Point getTargetLocation(java.awt.Window window) {
        java.awt.GraphicsEnvironment ge = java.awt.GraphicsEnvironment.getLocalGraphicsEnvironment();
        java.awt.GraphicsConfiguration gc = ge.getDefaultScreenDevice().getDefaultConfiguration();
        java.awt.Rectangle screenBounds = gc.getBounds();
        java.awt.Insets screenInsets = java.awt.Toolkit.getDefaultToolkit().getScreenInsets(gc);

        int marginX = 8;
        int marginY = 0; // flush up to taskbar

        int x = screenBounds.x + screenBounds.width - screenInsets.right - window.getWidth() - marginX;
        int y = screenBounds.y + screenBounds.height - screenInsets.bottom - window.getHeight() - marginY;

        x = Math.max(screenBounds.x, x);
        y = Math.max(screenBounds.y, y);

        return new java.awt.Point(x, y);
    }

    private static long lastShowTime = 0;

    /**
     * Displays this panel inside a JDialog window with a smooth slide-up animation
     * from the bottom up to the taskbar, and automatically closes it when clicking outside.
     */
    public static void showInDialog() {
        long now = System.currentTimeMillis();
        if (now - lastShowTime < 350) {
            return;
        }
        lastShowTime = now;

        javax.swing.SwingUtilities.invokeLater(() -> {
            if (slideTimer != null && slideTimer.isRunning()) {
                slideTimer.stop();
            }

            if (dialogInstance != null && dialogInstance.isVisible()) {
                java.awt.Point targetLoc = getTargetLocation(dialogInstance);
                dialogInstance.setLocation(targetLoc.x, targetLoc.y);
                dialogInstance.toFront();
                dialogInstance.requestFocus();
                if (currentInstance != null) {
                    currentInstance.refreshStatus();
                }
                return;
            }

            if (dialogInstance == null || !dialogInstance.isDisplayable()) {
                dialogInstance = new javax.swing.JDialog();
                dialogInstance.setTitle("Sync Progress");
                dialogInstance.setDefaultCloseOperation(javax.swing.JDialog.DISPOSE_ON_CLOSE);
                dialogInstance.setUndecorated(true);
                dialogInstance.setAlwaysOnTop(true);
                dialogInstance.setResizable(false);

                java.awt.Color borderColor = javax.swing.UIManager.getColor("Component.borderColor");
                if (borderColor == null) {
                    borderColor = new java.awt.Color(160, 160, 160);
                }
                dialogInstance.getRootPane().setBorder(javax.swing.BorderFactory.createLineBorder(borderColor, 1));

                currentInstance = new SystemTrayPanel();
                dialogInstance.setContentPane(currentInstance);
                dialogInstance.pack();

                try {
                    java.net.URL iconUrl = SystemTrayPanel.class.getResource("/icons/app-icon-mini.png");
                    if (iconUrl != null) {
                        dialogInstance.setIconImage(new javax.swing.ImageIcon(iconUrl).getImage());
                    }
                } catch (Exception ignored) {
                }

                // Automatically close when the user clicks somewhere else (loses focus)
                dialogInstance.addWindowFocusListener(new java.awt.event.WindowAdapter() {
                    @Override
                    public void windowLostFocus(java.awt.event.WindowEvent e) {
                        closePanel();
                    }
                });
            }

            java.awt.Point targetLoc = getTargetLocation(dialogInstance);
            int finalX = targetLoc.x;
            int finalY = targetLoc.y;
            int panelHeight = dialogInstance.getHeight();

            // Start position: just below the resting position (slides up from taskbar)
            int startY = finalY + panelHeight;
            dialogInstance.setLocation(finalX, startY);
            dialogInstance.setVisible(true);
            dialogInstance.toFront();
            dialogInstance.requestFocus();
            if (currentInstance != null) {
                currentInstance.refreshStatus();
            }

            long startTime = System.currentTimeMillis();
            final int duration = 180; // ms for smooth, responsive slide-up

            slideTimer = new javax.swing.Timer(10, null);
            slideTimer.addActionListener(e -> {
                long elapsed = System.currentTimeMillis() - startTime;
                float progress = Math.min(1.0f, elapsed / (float) duration);

                // Cubic ease-out: starts fast and gently slows down into resting position
                float ease = 1.0f - (float) Math.pow(1.0f - progress, 3);
                int currentY = Math.round(startY + (finalY - startY) * ease);

                if (dialogInstance != null && dialogInstance.isDisplayable()) {
                    dialogInstance.setLocation(finalX, currentY);
                }

                if (progress >= 1.0f) {
                    slideTimer.stop();
                    if (dialogInstance != null && dialogInstance.isDisplayable()) {
                        dialogInstance.setLocation(finalX, finalY);
                    }
                }
            });
            slideTimer.start();
        });
    }

