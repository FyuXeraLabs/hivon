    private void printAllCustomers() {
        FormSummaryPdfExporter.Builder builder = FormSummaryPdfExporter.builder()
                .title("Customer Master (MAS04)")
                .subtitle("Total Customers: " + allCustomers.size())
                .addDetail("Report Type", "Customer Master Catalog")
                .addDetail("Generated Date", java.time.LocalDate.now().toString())
                .addDetail("Total Records", String.valueOf(allCustomers.size()))
                .tableColumns(new String[]{"Code", "Customer Name", "Contact Person", "Phone", "Email", "Address"});

        for (CustomerDTO c : allCustomers) {
            builder.addTableRow(new String[]{
                safeString(c.getCustomerCode()),
                safeString(c.getCustomerName()),
                safeString(c.getContactPerson()),
                safeString(c.getPhone()),
                safeString(c.getEmail()),
                safeString(c.getAddress())
            });
        }

        builder.showExportDialog(this);
    }

    private static String safeString(String str) {
        return str != null ? str : "";
    }

    // loads and populates customer data into the table

    private void loadCustomerList() {
        createLoadCustomersTask().executeWithRetry();
    }

    private BackgroundTask createLoadCustomersTask() {
        return new BackgroundTask(this, "Loading Customers") {
            private List<CustomerDTO> customers;

            @Override
            protected Boolean performTask() throws Exception {
                updateProgress("Fetching customers...");
                customers = controller.getAllCustomers();
                return customers != null;
            }

            @Override
            protected void onSuccess() {
                populateCustomerTable(customers);
            }

            @Override
            protected void onFailure(Exception e) {
                // handled by retry/cancel on progress dialog
            }

            @Override
            protected void onCancel() {
                if (isInitializing) {
                    dispose();
                    throw new RuntimeException("Cancelled form loading due to fetch failure.");
                } else {
                    StatusMessageHandler.showError(txtStatus, "Failed to load customers!");
                }
            }

            @Override
            protected BackgroundTask createRetryTask() {
                return createLoadCustomersTask();
            }
        };
    }

    private void populateCustomerTable(List<CustomerDTO> customers) {
        this.allCustomers = customers;
        DefaultTableModel model = (DefaultTableModel) tblCustomers.getModel();
        model.setRowCount(0);

        if (customers != null) {
            for (CustomerDTO c : customers) {
                model.addRow(new Object[]{
                    c.getCustomerCode(),
                    c.getCustomerName(),
                    c.getContactPerson(),
                    c.getPhone()
                });
            }
        }
    }

    private CustomerDTO findCustomerByCode(String code) {
        if (code == null || allCustomers == null) return null;
        for (CustomerDTO c : allCustomers) {
            if (c.getCustomerCode().equals(code)) return c;
        }
        return null;
    }

